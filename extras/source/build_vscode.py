def a(color, alpha):
    """Palette color (or hex) plus alpha (0-1), as #RRGGBBAA."""
    hexv = C.get(color, color).lstrip("#")[:6]
    return f"#{hexv}{round(alpha * 255):02X}"


def c(name):
    return C[name]


def syn(role):
    color, style = R["syntax"][role]
    s = {"foreground": C[color]}
    if style:
        s["fontStyle"] = style
    return s


